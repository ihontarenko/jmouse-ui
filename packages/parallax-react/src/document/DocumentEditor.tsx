import { useParallaxTransport } from "../providers/ParallaxTransportProvider";
import { useCallback, useEffect, useRef, useState } from "react";
import type { DocumentForm, FormEdit } from "@jmouse/parallax";
import { ApiProblem } from "@jmouse/parallax";

export interface DocumentFormState {
  /** The form generated from the text; null until the first answer. */
  form: DocumentForm | null;
  /** A failure to read the text or to apply an edit, in words. */
  failure: string | null;
  /** An edit is being applied. */
  busy: boolean;
  /** Applies an edit made in the form as a patch of the text. */
  edit: (change: FormEdit) => void;
}

/**
 * One jMX document, edited as a form or as code — two windows on one text (DECISIONS §17). The form is generated by
 * the server from the text on every change, and an edit made in it is a patch of the text, so comments, order and
 * formatting survive either way. The same component edits every kind; how a block is shown is decided by the block.
 *
 * This hook keeps the form beside the text; the page draws it (`DocumentFormView`) and the code.
 */
export function useDocumentForm(source: string, onSourceChange: (source: string) => void): DocumentFormState {
  const transport = useParallaxTransport();
  const [form, setForm] = useState<DocumentForm | null>(null);
  const [failure, setFailure] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const latest = useRef(source);
  latest.current = source;
  // The text the form on screen was built from: an edit brings its own form, so its text is not read twice.
  const formSource = useRef<string | null>(null);
  // Edits are applied one after another, each to the text the previous one produced.
  const queue = useRef<Promise<void>>(Promise.resolve());

  // The form follows the text: after loading, and after typing in the code view settles.
  useEffect(() => {
    if (formSource.current === source) {
      return;
    }
    const controller = new AbortController();
    const timer = window.setTimeout(() => {
      transport.documents.form(source, controller.signal)
        .then((answer) => {
          if (answer.source === latest.current) {
            formSource.current = answer.source;
            setForm(answer.form);
            setFailure(null);
          }
        })
        .catch((problem) => {
          if (!controller.signal.aborted) {
            setFailure(problem instanceof ApiProblem ? problem.detail : "The document could not be read.");
          }
        });
    }, form ? 300 : 0);
    return () => {
      controller.abort();
      window.clearTimeout(timer);
    };
    // The form is fetched for the text; the form itself is not a reason to fetch again.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [source]);

  const edit = useCallback((change: FormEdit) => {
    queue.current = queue.current.then(async () => {
      setBusy(true);
      try {
        const answer = await transport.documents.edit(latest.current, change);
        latest.current = answer.source;
        formSource.current = answer.source;
        setForm(answer.form);
        setFailure(null);
        onSourceChange(answer.source);
      } catch (problem) {
        setFailure(problem instanceof ApiProblem ? problem.detail : "The change could not be applied.");
      } finally {
        setBusy(false);
      }
    });
  }, [onSourceChange]);

  return { form, failure, busy, edit };
}
